"use client";

import React, { useState } from "react";
import Link from "next/link";
import {
  Tag,
  ArrowLeft,
  Copy,
  Check,
  Download,
  ExternalLink,
  Sparkles,
  PlaySquare,
  Search,
  Hash,
  FileText,
  AlertCircle,
  Loader2,
} from "lucide-react";
import { useApp } from "@/context/AppContext";

export default function YouTubeTagsPage() {
  const { lang, t } = useApp();
  const [url, setUrl] = useState("https://www.youtube.com/watch?v=dQw4w9WgXcQ");
  const [loading, setLoading] = useState(false);
  const [copied, setCopied] = useState<"tags" | "hashtags" | null>(null);
  const [videoInfo, setVideoInfo] = useState<{
    title: string;
    author: string;
    thumbnail: string;
    videoId: string;
  } | null>(null);
  const [tags, setTags] = useState<string[]>([]);
  const [error, setError] = useState<string | null>(null);

  const extractVideoId = (inputUrl: string): string | null => {
    const regExp = /^.*(youtu.be\/|v\/|u\/\w\/|embed\/|watch\?v=|\&v=)([^#\&\?]*).*/;
    const match = inputUrl.match(regExp);
    return match && match[2].length === 11 ? match[2] : null;
  };

  const handleExtract = async (e?: React.FormEvent) => {
    if (e) e.preventDefault();
    setError(null);

    const vidId = extractVideoId(url);
    if (!vidId) {
      setError(
        lang === "bn"
          ? "অনুগ্রহ করে একটি সঠিক ইউটিউব ভিডিওর লিংক দিন (যেমন: https://www.youtube.com/watch?v=...)"
          : "Please provide a valid YouTube video URL"
      );
      return;
    }

    setLoading(true);

    try {
      // Fetch oEmbed data for actual video title and author
      const res = await fetch(`https://noembed.com/embed?url=https://www.youtube.com/watch?v=${vidId}`);
      const data = await res.json();

      const title = data.title || "YouTube Video";
      const author = data.author_name || "YouTube Creator";
      const thumbnail = `https://img.youtube.com/vi/${vidId}/maxresdefault.jpg`;

      setVideoInfo({
        title,
        author,
        thumbnail,
        videoId: vidId,
      });

      // Generate rich SEO tags based on actual title, author, and niche keywords
      const titleWords = title
        .replace(/[^\w\s\u0980-\u09FF]/gi, " ")
        .split(/\s+/)
        .map((w: string) => w.trim().toLowerCase())
        .filter((w: string) => w.length > 2);

      const generatedSet = new Set<string>();

      // 1. Author and channel
      generatedSet.add(author.toLowerCase());
      generatedSet.add(`${author.toLowerCase()} video`);

      // 2. High relevance phrases from title
      if (titleWords.length >= 2) {
        for (let i = 0; i < titleWords.length - 1; i++) {
          generatedSet.add(`${titleWords[i]} ${titleWords[i + 1]}`);
        }
      }

      // 3. Individual prominent keywords
      titleWords.forEach((word: string) => {
        if (!["the", "and", "for", "with", "from", "this", "that", "how", "what", "are", "you"].includes(word)) {
          generatedSet.add(word);
        }
      });

      // 4. Evergreen YouTube growth tags
      generatedSet.add("viral");
      generatedSet.add("trending video");
      generatedSet.add("official video");
      generatedSet.add("hd");
      generatedSet.add("best video 2026");
      generatedSet.add("bangla viral");
      generatedSet.add("youtube seo");

      const finalTags = Array.from(generatedSet).slice(0, 25);
      setTags(finalTags);
    } catch (err) {
      console.warn("oEmbed fetch failed, using fallback:", err);
      // Fallback
      setVideoInfo({
        title: "YouTube Video",
        author: "Content Creator",
        thumbnail: `https://img.youtube.com/vi/${vidId}/hqdefault.jpg`,
        videoId: vidId,
      });
      setTags([
        "trending",
        "viral video",
        "official hd",
        "youtube video",
        "bangladesh",
        "popular content",
        "seo tags",
        "top ranking",
        `video_${vidId}`,
      ]);
    } finally {
      setLoading(false);
    }
  };

  const copyTags = (asHashtags = false) => {
    if (tags.length === 0) return;
    const textToCopy = asHashtags
      ? tags.map((t) => `#${t.replace(/\s+/g, "")}`).join(" ")
      : tags.join(", ");

    navigator.clipboard.writeText(textToCopy);
    setCopied(asHashtags ? "hashtags" : "tags");
    setTimeout(() => setCopied(null), 2000);
  };

  const downloadTags = () => {
    if (tags.length === 0) return;
    const content = `YouTube SEO Tags for: ${videoInfo?.title || "Video"}\n` +
      `Extracted: ${new Date().toLocaleDateString()}\n\n` +
      `Comma Separated:\n${tags.join(", ")}\n\n` +
      `Hashtags:\n${tags.map((t) => `#${t.replace(/\s+/g, "")}`).join(" ")}\n\n` +
      `Generated by ToolKaj.com - 100% Free SEO Tools`;

    const blob = new Blob([content], { type: "text/plain;charset=utf-8" });
    const link = document.createElement("a");
    link.href = URL.createObjectURL(blob);
    link.download = `youtube_tags_${videoInfo?.videoId || "seo"}.txt`;
    link.click();
  };

  const totalChars = tags.join(", ").length;

  return (
    <div className="w-full py-12 bg-slate-50 dark:bg-slate-950 min-h-screen">
      <div className="max-w-4xl mx-auto px-4 sm:px-6 lg:px-8">
        {/* Breadcrumb */}
        <div className="flex items-center gap-2 text-xs text-slate-500 mb-6">
          <Link href="/" className="hover:text-indigo-600 flex items-center gap-1">
            <ArrowLeft className="w-3.5 h-3.5" /> {lang === "bn" ? "হোম" : "Home"}
          </Link>
          <span>/</span>
          <Link href="/category/social" className="hover:text-indigo-600">
            {lang === "bn" ? "সোশ্যাল মিডিয়া" : "Social Media"}
          </Link>
          <span>/</span>
          <span className="text-slate-800 dark:text-slate-200 font-semibold">
            {lang === "bn" ? "ইউটিউব ট্যাগ এক্সট্র্যাক্টর" : "YouTube Tags Extractor"}
          </span>
        </div>

        {/* Header */}
        <div className="mb-8">
          <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-red-100 text-red-700 dark:bg-red-950/60 dark:text-red-300 text-xs font-semibold mb-3">
            <PlaySquare className="w-3.5 h-3.5" />
            <span>{lang === "bn" ? "ইউটিউব এসইও টুল" : "YouTube SEO Tool"}</span>
          </div>
          <h1 className="text-2xl sm:text-4xl font-extrabold text-slate-900 dark:text-white">
            {lang === "bn" ? "ইউটিউব ট্যাগ ও এসইও এক্সট্র্যাক্টর" : "YouTube Tags & SEO Extractor"}
          </h1>
          <p className="text-slate-600 dark:text-slate-400 text-sm sm:text-base mt-2">
            {lang === "bn"
              ? "যেকোনো ইউটিউব ভিডিওর ভাইরাল ট্যাগ, মেটাডাটা ও কিওয়ার্ড এক্সট্র্যাক্ট করুন এবং ভিডিওর র‍্যাংকিং বাড়ান।"
              : "Extract viral tags, keywords, and SEO metadata from any YouTube video to boost your video ranking."}
          </p>
        </div>

        {/* Input Card */}
        <div className="bg-white dark:bg-slate-900 rounded-3xl border border-slate-200 dark:border-slate-800 p-6 sm:p-8 shadow-sm space-y-6">
          <form onSubmit={handleExtract} className="space-y-4">
            <div>
              <label className="text-xs font-bold text-slate-700 dark:text-slate-300 block mb-2">
                {lang === "bn" ? "ইউটিউব ভিডিওর লিংক দিন" : "Enter YouTube Video URL"}
              </label>
              <div className="flex flex-col sm:flex-row gap-2">
                <div className="relative flex-1">
                  <div className="absolute inset-y-0 left-0 pl-3.5 flex items-center pointer-events-none text-slate-400">
                    <PlaySquare className="w-5 h-5 text-red-500" />
                  </div>
                  <input
                    type="url"
                    value={url}
                    onChange={(e) => setUrl(e.target.value)}
                    placeholder="https://www.youtube.com/watch?v=..."
                    required
                    className="w-full pl-11 pr-4 py-3 rounded-2xl bg-slate-50 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 text-sm focus:outline-none focus:ring-2 focus:ring-red-500 font-mono"
                  />
                </div>
                <button
                  type="submit"
                  disabled={loading}
                  className="px-8 py-3 rounded-2xl bg-red-600 hover:bg-red-700 disabled:opacity-50 text-white font-bold text-sm shadow-md flex items-center justify-center gap-2 transition-all shrink-0"
                >
                  {loading ? (
                    <>
                      <Loader2 className="w-4 h-4 animate-spin" />
                      <span>{lang === "bn" ? "ট্যাগ বের হচ্ছে..." : "Extracting..."}</span>
                    </>
                  ) : (
                    <>
                      <Search className="w-4 h-4" />
                      <span>{lang === "bn" ? "ট্যাগ খুঁজুন" : "Find Tags"}</span>
                    </>
                  )}
                </button>
              </div>
            </div>

            {error && (
              <div className="p-3.5 rounded-xl bg-rose-50 dark:bg-rose-950/40 border border-rose-200 dark:border-rose-900 text-xs text-rose-700 dark:text-rose-300 flex items-center gap-2">
                <AlertCircle className="w-4 h-4 shrink-0" />
                <span>{error}</span>
              </div>
            )}
          </form>

          {/* Video Metadata Preview */}
          {videoInfo && (
            <div className="p-4 sm:p-5 rounded-2xl bg-slate-50 dark:bg-slate-800/60 border border-slate-200 dark:border-slate-700 flex flex-col sm:flex-row gap-4 items-center">
              <div className="w-full sm:w-44 aspect-video rounded-xl overflow-hidden bg-black shrink-0 relative shadow-sm">
                <img
                  src={videoInfo.thumbnail}
                  alt={videoInfo.title}
                  className="w-full h-full object-cover"
                  onError={(e) => {
                    (e.target as HTMLImageElement).src = `https://img.youtube.com/vi/${videoInfo.videoId}/hqdefault.jpg`;
                  }}
                />
              </div>
              <div className="flex-1 space-y-1 text-center sm:text-left">
                <span className="text-[11px] font-bold text-red-600 dark:text-red-400 uppercase tracking-widest block">
                  {videoInfo.author}
                </span>
                <h3 className="text-base font-extrabold text-slate-900 dark:text-white line-clamp-2">
                  {videoInfo.title}
                </h3>
                <a
                  href={`https://www.youtube.com/watch?v=${videoInfo.videoId}`}
                  target="_blank"
                  rel="noopener noreferrer"
                  className="inline-flex items-center gap-1 text-xs text-indigo-600 dark:text-indigo-400 hover:underline pt-1 font-semibold"
                >
                  <span>{lang === "bn" ? "ইউটিউবে দেখুন" : "Watch on YouTube"}</span>
                  <ExternalLink className="w-3 h-3" />
                </a>
              </div>
            </div>
          )}

          {/* Extracted Tags Section */}
          {tags.length > 0 && (
            <div className="space-y-4 pt-2 border-t border-slate-100 dark:border-slate-800">
              <div className="flex flex-wrap items-center justify-between gap-3">
                <div className="flex items-center gap-2">
                  <span className="text-sm font-black text-slate-900 dark:text-white">
                    {lang === "bn" ? `এক্সট্র্যাক্ট করা ট্যাগসমূহ (${tags.length}টি)` : `Extracted Tags (${tags.length})`}
                  </span>
                  <span
                    className={`text-[11px] px-2.5 py-0.5 rounded-full font-bold ${
                      totalChars <= 500
                        ? "bg-emerald-100 text-emerald-800 dark:bg-emerald-950 dark:text-emerald-300"
                        : "bg-amber-100 text-amber-800 dark:bg-amber-950 dark:text-amber-300"
                    }`}
                  >
                    {totalChars} / 500 {lang === "bn" ? "ক্যারেক্টার" : "chars"}
                  </span>
                </div>

                <div className="flex flex-wrap items-center gap-2">
                  <button
                    onClick={() => copyTags(false)}
                    className="px-3.5 py-1.5 rounded-xl bg-slate-100 dark:bg-slate-800 hover:bg-slate-200 dark:hover:bg-slate-700 text-slate-700 dark:text-slate-300 font-bold text-xs flex items-center gap-1.5 shadow-sm transition-all"
                  >
                    {copied === "tags" ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5" />}
                    <span>{copied === "tags" ? (lang === "bn" ? "কপি হয়েছে!" : "Copied!") : (lang === "bn" ? "সব ট্যাগ কপি" : "Copy Tags")}</span>
                  </button>

                  <button
                    onClick={() => copyTags(true)}
                    className="px-3.5 py-1.5 rounded-xl bg-slate-100 dark:bg-slate-800 hover:bg-slate-200 dark:hover:bg-slate-700 text-slate-700 dark:text-slate-300 font-bold text-xs flex items-center gap-1.5 shadow-sm transition-all"
                  >
                    {copied === "hashtags" ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Hash className="w-3.5 h-3.5" />}
                    <span>{copied === "hashtags" ? (lang === "bn" ? "কপি হয়েছে!" : "Copied!") : (lang === "bn" ? "হ্যাশট্যাগ কপি" : "Copy Hashtags")}</span>
                  </button>

                  <button
                    onClick={downloadTags}
                    className="px-3.5 py-1.5 rounded-xl bg-red-50 dark:bg-red-950/50 hover:bg-red-100 text-red-700 dark:text-red-300 font-bold text-xs flex items-center gap-1.5 shadow-sm transition-all border border-red-200 dark:border-red-900"
                  >
                    <Download className="w-3.5 h-3.5" />
                    <span>TXT {lang === "bn" ? "ডাউনলোড" : "Download"}</span>
                  </button>
                </div>
              </div>

              {/* Tag Badges Grid */}
              <div className="flex flex-wrap gap-2 p-4 rounded-2xl bg-slate-50 dark:bg-slate-800/40 border border-slate-200 dark:border-slate-800 max-h-72 overflow-y-auto">
                {tags.map((tag, idx) => (
                  <span
                    key={idx}
                    onClick={() => {
                      navigator.clipboard.writeText(tag);
                    }}
                    title="Click to copy this tag"
                    className="cursor-pointer group inline-flex items-center gap-1 px-3 py-1.5 rounded-xl bg-white dark:bg-slate-800 border border-slate-200 dark:border-slate-700 text-xs font-semibold text-slate-800 dark:text-slate-200 hover:border-red-500 hover:text-red-600 dark:hover:border-red-500 transition-all shadow-sm"
                  >
                    <span>#{tag}</span>
                    <Copy className="w-3 h-3 opacity-0 group-hover:opacity-100 text-slate-400" />
                  </span>
                ))}
              </div>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
