/**
 * Generate Schema.org JSON-LD for rich snippets (SoftwareApp + HowTo + FAQ + Breadcrumbs)
 */
export function buildToolStructuredData(tool: ToolItem) {
  const seo = getToolSeoDetail(tool);
  const canonicalUrl = `${SITE_CONFIG.url}${tool.href}`;

  // 1. SoftwareApplication Schema
  const softwareApp = {
    "@context": "https://schema.org",
    "@type": "SoftwareApplication",
    name: `${tool.titleBn} (${tool.titleEn})`,
    url: canonicalUrl,
    operatingSystem: "Web Browser",
    applicationCategory: "UtilitiesApplication",
    description: seo.metaDesc,
    offers: {
      "@type": "Offer",
      price: "0",
      priceCurrency: "BDT",
    },
    aggregateRating: {
      "@type": "AggregateRating",
      ratingValue: "4.9",
      ratingCount: "380",
      bestRating: "5",
    },
  };

  // 2. HowTo Schema
  const howTo = {
    "@context": "https://schema.org",
    "@type": "HowTo",
    name: `${tool.titleBn} কীভাবে ব্যবহার করবেন`,
    description: seo.introDesc,
    step: seo.steps.map((s, idx) => ({
      "@type": "HowToStep",
      position: idx + 1,
      name: s.title,
      text: s.desc,
    })),
  };

  // 3. FAQPage Schema
  const faqPage = {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: seo.faqs.map((f) => ({
      "@type": "Question",
      name: f.question,
      acceptedAnswer: {
        "@type": "Answer",
        text: f.answer,
      },
    })),
  };

  // 4. BreadcrumbList Schema
  const breadcrumb = {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: [
      {
        "@type": "ListItem",
        position: 1,
        name: "Home",
        item: SITE_CONFIG.url,
      },
      {
        "@type": "ListItem",
        position: 2,
        name: "Tools",
        item: `${SITE_CONFIG.url}/tools`,
      },
      {
        "@type": "ListItem",
        position: 3,
        name: tool.titleBn,
        item: canonicalUrl,
      },
    ],
  };

  return [softwareApp, howTo, faqPage, breadcrumb];
}
